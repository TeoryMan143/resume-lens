"""Stage 4 — HTML visualization of a validated candidate profile.

The page is generated only from the textX model of a CPL document, so whatever
it shows has already passed the lexical, syntactic and semantic checks.
The output is a single self-contained HTML file (inline CSS, no scripts).
"""

from __future__ import annotations

from html import escape
from pathlib import Path
from typing import Any

