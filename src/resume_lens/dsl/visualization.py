LABEL_WORDS = {"Devops": "DevOps"}


def profile_label(name: str) -> str:
    """FULL_STACK_DEVELOPER -> Full Stack Developer."""
    words = name.replace("_", " ").title().split()
    return " ".join(LABEL_WORDS.get(w, w) for w in words)


def _href(link: str) -> str:
    return link if link.startswith(("http://", "https://")) else f"https://{link}"


class ProfileHtmlRenderer:
    """Renders the textX model of a CPL document as an HTML page."""

    def render(self, model: Any, source: str | None = None) -> str:
        sections = [
            self._header(model),
            self._summary(model),
            self._classification(model),
            self._skills(model),
            self._experience(model),
            self._education(model),
            self._source(source),
        ]
        body = "\n".join(s for s in sections if s)
        return (
            "<!DOCTYPE html>\n"
            '<html lang="en">\n<head>\n<meta charset="utf-8">\n'
            '<meta name="viewport" content="width=device-width, initial-scale=1">\n'
            f"<title>{escape(model.name)} · ResumeLens</title>\n"
            f"<style>{STYLE}</style>\n</head>\n<body>\n<main>\n{body}\n"
            "<footer>Generated by ResumeLens from a validated candidate profile. "
            "It states which qualification patterns are satisfied by the qualifications "
            "explicitly found in the résumé; it is not a ranking or a hiring decision."
            "</footer>\n</main>\n</body>\n</html>\n"
        )

    def save(self, model: Any, path: str | Path, source: str | None = None) -> Path:
        path = Path(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(self.render(model, source), encoding="utf-8")
        return path

    # -- sections ------------------------------------------------------------
    def _header(self, model) -> str:
        items = []
        for entry in model.contact.entries if model.contact else []:
            value = escape(entry.value)
            kind = entry.__class__.__name__
            if kind == "EmailEntry":
                items.append(f'<li><a href="mailto:{value}">{value}</a></li>')
            elif kind == "PhoneEntry":
                tel = escape("".join(c for c in entry.value if c.isdigit() or c == "+"))
                items.append(f'<li><a href="tel:{tel}">{value}</a></li>')
            else:
                items.append(
                    f'<li><a href="{escape(_href(entry.value))}">{value}</a></li>'
                )
        contact = f'\n<ul class="contact">{"".join(items)}</ul>' if items else ""
        return f"<header>\n<h1>{escape(model.name)}</h1>{contact}\n</header>"

    def _summary(self, model) -> str:
        accepted = [
            v.profile for v in model.classification.verdicts if v.status == "ACCEPTED"
        ]
        if accepted:
            badges = "".join(
                f'<span class="badge accepted">{escape(profile_label(p))}</span>'
                for p in accepted
            )
            text = "Satisfies the qualification pattern of"
        else:
            badges = '<span class="badge rejected">None</span>'
            text = "Satisfies no qualification pattern"
        return (
            f'<section class="card summary" aria-label="Summary">'
            f"<span>{text}</span> {badges}</section>"
        )

    def _classification(self, model) -> str:
        rows = []
        for v in model.classification.verdicts:
            status = v.status.lower()
            if v.status == "ACCEPTED":
                detail = (
                    '<div class="muted">Sequence read by the automaton:</div>'
                    + self._chips(v.sequence)
                )
            elif v.missing:
                detail = (
                    f'<div class="muted">First unsatisfied stage: '
                    f'<span class="chip">{escape(v.missing)}</span></div>'
                )
            else:
                detail = '<div class="muted">Pattern not satisfied.</div>'
            rows.append(
                f'<li><div class="verdict-head"><span>{escape(profile_label(v.profile))}</span>'
                f'<span class="badge {status}">{escape(v.status)}</span></div>{detail}</li>'
            )
        return (
            '<section class="card">\n<h2>Profile classification</h2>\n'
            f'<ul class="verdicts">{"".join(rows)}</ul>\n</section>'
        )

    def _skills(self, model) -> str:
        parts = []
        for group in model.skills.groups:
            chips = "".join(
                f'<li class="chip" title="{escape(", ".join(s.aliases))}">{escape(s.token)}'
                + (
                    f" <small>{escape(', '.join(s.aliases))}</small>"
                    if s.aliases
                    else ""
                )
                + "</li>"
                for s in group.skills
            )
            label = CATEGORY_LABELS.get(group.category, group.category)
            parts.append(f'<h3>{escape(label)}</h3>\n<ul class="chips">{chips}</ul>')
        if model.skills.unrecognized:
            values = ", ".join(escape(v) for v in model.skills.unrecognized.values)
            parts.append(f'<h3>Not recognized</h3>\n<p class="muted">{values}</p>')
        if not parts:
            parts.append('<p class="muted">No qualifications were identified.</p>')
        return (
            '<section class="card">\n<h2>Skills</h2>\n'
            + "\n".join(parts)
            + "\n</section>"
        )

    def _experience(self, model) -> str:
        if not model.experience:
            return ""
        items = []
        for e in model.experience.entries:
            years = f"{e.years} {'year' if e.years == 1 else 'years'}"
            field = f" — {escape(e.field)}" if e.field else ""
            items.append(f"<li><strong>{years}</strong>{field}</li>")
        return (
            '<section class="card">\n<h2>Experience</h2>\n'
            f'<ul class="plain">{"".join(items)}</ul>\n</section>'
        )

    def _education(self, model) -> str:
        if not model.education:
            return ""
        items = "".join(f"<li>{escape(d.title)}</li>" for d in model.education.degrees)
        return (
            '<section class="card">\n<h2>Education</h2>\n'
            f'<ul class="plain">{items}</ul>\n</section>'
        )

    @staticmethod
    def _source(source: str | None) -> str:
        if not source:
            return ""
        return (
            '<section class="card">\n<details><summary>Candidate profile (CPL source)</summary>'
            f"<pre>{escape(source)}</pre></details>\n</section>"
        )

    @staticmethod
    def _chips(tokens) -> str:
        return (
            '<ul class="chips">'
            + "".join(f'<li class="chip">{escape(t)}</li>' for t in tokens)
            + "</ul>"
        )
